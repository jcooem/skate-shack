import "server-only";
import { betterAuth } from "better-auth";
import { prismaAdapter } from "better-auth/adapters/prisma";
import { nextCookies } from "better-auth/next-js";
import { prisma } from "@/lib/db";
import { actionEmail, sendEmail } from "@/lib/email";
import { getSettings } from "@/lib/settings";
import type { SocialProviderId } from "@/lib/constants";

async function businessName() {
  try {
    return (await getSettings()).businessName;
  } catch {
    return "Skate Shack";
  }
}

const socialProviders = {
  ...(process.env.GOOGLE_CLIENT_ID && process.env.GOOGLE_CLIENT_SECRET
    ? { google: { clientId: process.env.GOOGLE_CLIENT_ID, clientSecret: process.env.GOOGLE_CLIENT_SECRET } }
    : {}),
  ...(process.env.FACEBOOK_CLIENT_ID && process.env.FACEBOOK_CLIENT_SECRET
    ? { facebook: { clientId: process.env.FACEBOOK_CLIENT_ID, clientSecret: process.env.FACEBOOK_CLIENT_SECRET } }
    : {}),
  ...(process.env.MICROSOFT_CLIENT_ID && process.env.MICROSOFT_CLIENT_SECRET
    ? {
        microsoft: {
          clientId: process.env.MICROSOFT_CLIENT_ID,
          clientSecret: process.env.MICROSOFT_CLIENT_SECRET,
          // "common" = personal Microsoft accounts (Outlook/Hotmail) + work/school accounts.
          tenantId: process.env.MICROSOFT_TENANT_ID || "common",
        },
      }
    : {}),
};

/** Social providers that have credentials configured (shown on the login page). */
export const enabledSocialProviders = Object.keys(socialProviders) as SocialProviderId[];

export const auth = betterAuth({
  appName: "Skate Shack",
  // On Render, RENDER_EXTERNAL_URL is set automatically (https://<service>.onrender.com).
  // Set BETTER_AUTH_URL when you use a custom domain.
  baseURL: process.env.BETTER_AUTH_URL || process.env.RENDER_EXTERNAL_URL,
  secret: process.env.BETTER_AUTH_SECRET,
  database: prismaAdapter(prisma, { provider: "postgresql" }),
  // IDs are generated by the database (cuid default in the Prisma schema).
  advanced: { database: { generateId: false } },

  emailAndPassword: {
    enabled: true,
    // A password account can't sign in until the email is proven, so nobody can
    // claim an existing customer's history just by knowing their email.
    requireEmailVerification: true,
    minPasswordLength: 8,
    resetPasswordTokenExpiresIn: 60 * 60 * 24, // 24 hours, since this is also "set your password"
    revokeSessionsOnPasswordReset: true,
    sendResetPassword: async ({ user, url }) => {
      const name = await businessName();
      await sendEmail({
        to: user.email,
        subject: `Set your ${name} password`,
        ...actionEmail({
          businessName: name,
          heading: "Choose your password",
          body: "Use the button below to choose a password for your account. You'll then be able to see your sharpening history and card balance.",
          cta: "Choose password",
          url,
        }),
      });
    },
    onPasswordReset: async ({ user }) => {
      // The reset link was delivered to this inbox, which proves ownership.
      await prisma.user.update({ where: { id: user.id }, data: { emailVerified: true } });
    },
  },

  emailVerification: {
    sendOnSignUp: true,
    sendOnSignIn: true,
    autoSignInAfterVerification: true,
    expiresIn: 60 * 60 * 24,
    sendVerificationEmail: async ({ user, url }) => {
      const name = await businessName();
      await sendEmail({
        to: user.email,
        subject: `Confirm your email for ${name}`,
        ...actionEmail({
          businessName: name,
          heading: "Confirm your email",
          body: "Please confirm this is your email address to finish signing in.",
          cta: "Confirm email",
          url,
        }),
      });
    },
  },

  socialProviders,

  account: {
    accountLinking: {
      enabled: true,
      // Google always verifies email addresses. Other providers link automatically
      // only when they report the email as verified; otherwise the customer can
      // connect them from their profile after signing in.
      trustedProviders: ["google"],
    },
  },

  session: {
    expiresIn: 60 * 60 * 24 * 30, // 30 days
    updateAge: 60 * 60 * 24,
  },

  // Must be last: lets Better Auth set cookies from Server Actions.
  plugins: [nextCookies()],
});
